export const AGENT_ROLE_MAP: Record<AgentId, AgentRoleDefinition> = Object.fromEntries(
  AGENT_ROLES.map((role) => [role.id, role]),
) as Record<AgentId, AgentRoleDefinition>;

export function getAgentRole(agentId: AgentId): AgentRoleDefinition {
  const role = AGENT_ROLE_MAP[agentId];
  if (!role) throw new Error(`Unknown agent role: ${agentId}`);
  return role;
}

/** Roles that can be selected for a given task type, best match first. */
export function rolesForTaskType(taskType: TaskType): AgentRoleDefinition[] {
  return AGENT_ROLES.filter((role) => role.handledTaskTypes.includes(taskType) && role.id !== 'supervisor');
}

